def ror32(val, n):
    return ((val >> n) | (val << (32 - n))) & 0xFFFFFFFF

def sub_word(w):
    return ((aes_sbox[(w >> 24) & 0xff] << 24) |
            (aes_sbox[(w >> 16) & 0xff] << 16) |
            (aes_sbox[(w >> 8) & 0xff] << 8) |
            aes_sbox[w & 0xff])

